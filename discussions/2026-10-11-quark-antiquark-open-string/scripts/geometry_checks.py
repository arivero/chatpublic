#!/usr/bin/env python3
"""Check algebra used in dual_qcd_cp2_s1.md; this does not solve a KK vacuum."""

import json
from pathlib import Path

import sympy as sp


def main():
    H, k, d = sp.symbols("H k d")
    td_cp2 = 1 + sp.Rational(3, 2)*H + H**2
    ahat_cp2 = 1 - H**2/8
    index_dolbeault = sp.expand(sp.series(sp.exp(k*H), H, 0, 3).removeO()*td_cp2).coeff(H, 2)
    index_spinc = sp.expand(sp.series(sp.exp(d*H/2), H, 0, 3).removeO()*ahat_cp2).coeff(H, 2)
    assert sp.simplify(index_dolbeault - (k+1)*(k+2)/2) == 0
    assert sp.simplify(index_spinc.subs(d, 2*k+3) - index_dolbeault) == 0

    def su3_dim(p, q):
        return sp.Rational((p+1)*(q+1)*(p+q+2), 2)

    def triality(p, q):
        return (p+2*q) % 3

    holomorphic_modes = []
    for kk in range(5):
        value = index_dolbeault.subs(k, kk)
        assert value == sp.binomial(kk+2, 2) == su3_dim(0, kk)
        holomorphic_modes.append({"twist_k": kk, "index": int(value),
                                  "SU3_rep_in_dual_fundamental_convention": [0, kk]})
    for kk in (-1, -2):
        assert index_dolbeault.subs(k, kk) == 0
    for kk in (-5, -4, -3):
        assert index_dolbeault.subs(k, kk) == sp.binomial(-kk-1, 2)

    ordinary_scalar_harmonics = []
    for pp in range(5):
        assert su3_dim(pp, pp) == (pp+1)**3
        assert triality(pp, pp) == 0
        ordinary_scalar_harmonics.append({"p": pp, "rep": [pp, pp], "dimension": int(su3_dim(pp, pp))})

    # Choose the diagonal quotient generated by (omega*I, exp(2*pi*i/3)).
    # Its descent condition is triality+n == 0 mod 3, with Q_em=n/3.
    endpoints = [{"label": "down-type", "triality": 1, "n": -1},
                 {"label": "up-type", "triality": 1, "n": 2}]
    for endpoint in endpoints:
        assert (endpoint["triality"] + endpoint["n"]) % 3 == 0
        endpoint["Q_em"] = str(sp.Rational(endpoint["n"], 3))
    meson_charges = sorted({sp.Rational(a["n"]-b["n"], 3) for a in endpoints for b in endpoints})
    assert meson_charges == [-1, 0, 1]
    assert su3_dim(1, 0)*su3_dim(0, 1) == su3_dim(0, 0)+su3_dim(1, 1)

    # The common-twist lower bound is analytic: |2+theta|+|-1+theta| >= 3.
    # Verify the minimizing midpoint saturates max >= 3/2.
    theta = sp.Rational(-1, 2)
    assert max(abs(2+theta), abs(-1+theta)) == sp.Rational(3, 2)

    nc, nf = 7, 10
    assert nc+1 < nf < sp.Rational(3, 2)*nc
    dual_example = {"electric_Nc": nc, "Nf": nf, "magnetic_Nc": nf-nc,
                    "electric_beta0": 3*nc-nf, "magnetic_beta0": 3*(nf-nc)-nf}
    assert dual_example["electric_beta0"] == 11
    assert dual_example["magnetic_beta0"] == -1

    # Illustrative low-energy gauge-theory hierarchy, not a gravitational KK solution.
    mkk, confinement = sp.Integer(10000), sp.Rational(1, 5)
    beta0_qcd = sp.Integer(7)  # Six Dirac flavors; thresholds deliberately omitted.
    alpha = 2*sp.pi/(beta0_qcd*sp.log(mkk/confinement))
    recovered_scale = mkk*sp.exp(-2*sp.pi/(beta0_qcd*alpha))
    assert sp.simplify(recovered_scale-confinement) == 0

    result = {
        "scope": "Exact index and representation algebra; illustrative scale estimates. No compactification field equations, dual QCD model, or scattering amplitudes solved.",
        "index_canonical_spinc_twisted_by_Ok": str(sp.factor(index_dolbeault)),
        "index_spinc_with_determinant_Od_d_odd": str(sp.factor(index_spinc)),
        "holomorphic_modes": holomorphic_modes,
        "ordinary_scalar_harmonics": ordinary_scalar_harmonics,
        "endpoint_charge_assignment": endpoints,
        "color_singlet_meson_charges": [str(q) for q in meson_charges],
        "minimum_common_twist_maximum_circle_mass_times_R": "3/2",
        "free_magnetic_SQCD_example": dual_example,
        "illustrative_dimensional_transmutation": {
            "M_KK_GeV": int(mkk), "Lambda_GeV": float(confinement),
            "Dirac_flavors": 6, "alpha_at_M_KK": float(alpha.evalf())},
        "checks_passed": [
            "Two index-theorem expressions agree under d=2k+3",
            "Holomorphic section counts match SU(3) representations and negative-twist cohomology counts",
            "Untwisted scalar harmonics have zero triality",
            "Quark-like charges obey the chosen center quotient and produce meson charges 0,+1,-1",
            "Common circle-twist mass bound is saturated at its minimizing midpoint",
            "SQCD example lies in the free-magnetic range and has the stated beta-function signs",
            "One-loop dimensional-transmutation example reproduces the specified scale"]}
    target = Path(__file__).resolve().parents[1]/"calculations"/"geometry_results.json"
    target.write_text(json.dumps(result, indent=2)+"\n")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
